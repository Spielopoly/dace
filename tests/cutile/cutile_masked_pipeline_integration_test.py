@dace.program
def pybe_ifelse_const_branch(A: dace.float32[16, 16], B: dace.float32[16, 16]):
    """A > 0 → B -= 1  else B += 1."""
    for i, j in dace.map[0:16, 0:16]:
        if A[i, j] > 0:
            B[i, j] = B[i, j] - 1.0
        else:
            B[i, j] = B[i, j] + 1.0


@dace.program
def pybe_ifelse_array_branch(
    A: dace.float32[16, 16],
    B: dace.float32[16, 16],
    C: dace.float32[16, 16],
):
    """A > 0 → C += B  else C -= B."""
    for i, j in dace.map[0:16, 0:16]:
        if A[i, j] > 0:
            C[i, j] = C[i, j] + B[i, j]
        else:
            C[i, j] = C[i, j] - B[i, j]


@dace.program
def pybe_ifelse_lt_branch(
    A: dace.float32[16, 16],
    B: dace.float32[16, 16],
    C: dace.float32[16, 16],
):
    """A < B → C = A + B  else C = A - B."""
    for i, j in dace.map[0:16, 0:16]:
        if A[i, j] < B[i, j]:
            C[i, j] = A[i, j] + B[i, j]
        else:
            C[i, j] = A[i, j] - B[i, j]


@dace.program
def pybe_ifelse_ge_sq_abs(A: dace.float32[16, 16], B: dace.float32[16, 16]):
    """A >= 0 → B = A*A  else B = abs(A)."""
    for i, j in dace.map[0:16, 0:16]:
        if A[i, j] >= 0:
            B[i, j] = A[i, j] * A[i, j]
        else:
            B[i, j] = abs(A[i, j])


@dace.program
def pybe_ifelse_le_const(A: dace.float32[16, 16], B: dace.float32[16, 16]):
    """A <= 0 → B = A * 3  else B = A / 2."""
    for i, j in dace.map[0:16, 0:16]:
        if A[i, j] <= 0:
            B[i, j] = A[i, j] * 3.0
        else:
            B[i, j] = A[i, j] / 2.0


@dace.program
def pybe_ifelse_ne_neg(A: dace.float32[16, 16], B: dace.float32[16, 16]):
    """A != 0 → B = -A  else B = A + 1."""
    for i, j in dace.map[0:16, 0:16]:
        if A[i, j] != 0:
            B[i, j] = -A[i, j]
        else:
            B[i, j] = A[i, j] + 1.0


@dace.program
def pybe_ifelse_float_mask(
    A: dace.float32[16, 16],
    B: dace.float32[16, 16],
    Mask: dace.float32[16, 16],
    C: dace.float32[16, 16],
):
    """if Mask > 0: C = A + B  else: C = C.  (Runtime boolean mask via float array.)"""
    for i, j in dace.map[0:16, 0:16]:
        if Mask[i, j] > 0:
            C[i, j] = A[i, j] + B[i, j]
        else:
            C[i, j] = C[i, j]


@dace.program
def pybe_ifelse_symbolic(_A: dace.float32[_SZ, _SZ], _B: dace.float32[_SZ, _SZ]):
    """Symbolic SZ: A > 0 → B -= 1  else B += 1."""
    for i, j in dace.map[0:_SZ, 0:_SZ]:
        if _A[i, j] > 0:
            _B[i, j] = _B[i, j] - 1.0
        else:
            _B[i, j] = _B[i, j] + 1.0


