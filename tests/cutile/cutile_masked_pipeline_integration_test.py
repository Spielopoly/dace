"""Full-pipeline integration tests for symbolic-masked and if-else cuTile operations.

This file fills the gap identified after the previous session: code-structure tests and
direct library-node C++ tests exist, but end-to-end GPU integration tests do not.

Node types generated by the pipeline and tested here:

  TileIfElseOpLibraryNode  (generated from @dace.program if-else branches)
    - Value-comparison conditions: A > 0, A < B, A >= 0, etc.
    - Boolean-like float mask input: `if Mask > 0`
    - All-true / all-false input edge cases
    - Symbolic array sizes

  TileSymbolicMaskedOpLibraryNode  (generated from strided @dace.program maps)
    - Stride-2 map in one dimension → even-element mask
    - Both-dimension stride → row-and-column mask
    - Non-square strided arrays
    - Verify only strided elements get updated (others preserved)

Both node types have Python-backend expansions.  Every GPU test here follows:
  @dace.program → to_sdfg() → sdfg.backend=Python → apply_cutile_pipeline()
  → sdfg.compile() → run on GPU → np.testing.assert_allclose(NumPy reference)

Note on TileRuntimeMaskedOpLibraryNode:
  This node type is NOT generated by apply_cutile_pipeline(); it is only
  created programmatically.  Its Python-backend expansion is exercised via the
  code-structure tests in cutile_masked_python_backend_test.py.  A boolean-mask
  condition expressed as `if Mask[i,j] > 0:` in a @dace.program produces a
  TileIfElseOpLibraryNode with the same runtime-mask semantics.
"""

