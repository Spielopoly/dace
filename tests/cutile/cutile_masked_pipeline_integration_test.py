@dace.program
def pybe_strided_i2_add(
    A: dace.float32[32, 16],
    B: dace.float32[32, 16],
    C: dace.float32[32, 16],
):
    """Stride-2 in i: only even rows get C[i,j] = A[i,j] + B[i,j]."""
    for i, j in dace.map[0:32:2, 0:16]:
        C[i, j] = A[i, j] + B[i, j]


@dace.program
def pybe_strided_i2_negate(A: dace.float32[32, 16], C: dace.float32[32, 16]):
    """Stride-2 in i: only even rows get C[i,j] = -A[i,j]."""
    for i, j in dace.map[0:32:2, 0:16]:
        C[i, j] = -A[i, j]


@dace.program
def pybe_strided_j2_mul(
    A: dace.float32[16, 32],
    B: dace.float32[16, 32],
    C: dace.float32[16, 32],
):
    """Stride-2 in j: only even columns get C[i,j] = A[i,j] * B[i,j]."""
    for i, j in dace.map[0:16, 0:32:2]:
        C[i, j] = A[i, j] * B[i, j]


@dace.program
def pybe_strided_offset_add(
    A: dace.float32[16, 16],
    B: dace.float32[16, 16],
    C: dace.float32[16, 16],
):
    """Non-zero start, stride-2 in i: rows 2,4,6,...,14 get updated."""
    for i, j in dace.map[2:16:2, 0:16]:
        C[i, j] = A[i, j] + B[i, j]


