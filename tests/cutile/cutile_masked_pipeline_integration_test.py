_SZ = dace.symbol("SZ", dtype=dace.int32)


def _frame_code_of(sdfg: dace.SDFG) -> str:
    code_objects = dace_codegen.generate_code(sdfg)
    return next(co.clean_code for co in code_objects if co.name == sdfg.name)


def _lib_nodes(sdfg: dace.SDFG):
    return [
        n
        for state in sdfg.states()
        for n in state.nodes()
        if isinstance(n, nodes.LibraryNode)
    ]


def _count(sdfg, cls):
    return sum(1 for n in _lib_nodes(sdfg) if isinstance(n, cls))


def _pipeline_py(sdfg: dace.SDFG, **kw) -> dace.SDFG:
    """Set Python backend and run the cuTile pipeline."""
    sdfg.backend = dtypes.BackendLanguage.Python
    apply_cutile_pipeline(sdfg, **kw)
    return sdfg


